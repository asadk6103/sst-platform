import sanitizeHtml from 'sanitize-html';

/** Rich-text sanitisation: keeps editorial formatting, strips scripts, styles, event handlers. */
export function sanitizeRich(html: string): string {
  return sanitizeHtml(html, {
    allowedTags: ['p', 'br', 'strong', 'b', 'em', 'i', 'u', 's', 'a', 'ul', 'ol', 'li', 'h2', 'h3', 'h4', 'blockquote', 'hr', 'span'],
    allowedAttributes: { a: ['href', 'target', 'rel'] },
    allowedSchemes: ['http', 'https', 'mailto', 'tel'],
    allowProtocolRelative: false,
    transformTags: {
      a: (tagName, attribs) => ({
        tagName,
        attribs: attribs.target === '_blank' ? { ...attribs, rel: 'noopener noreferrer' } : attribs,
      }),
    },
  }).trim();
}

/** Plain text: removes all markup. */
export const stripTags = (s: string) => sanitizeHtml(s, { allowedTags: [], allowedAttributes: {} });
